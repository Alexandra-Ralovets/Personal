/* ─────────────────── ПЕРЕВОД ГОТОВОЙ РАЗМЕТКИ ────────────────────────────
   Строки интерфейса не размечены в коде ключами: ключ — сама русская строка,
   а перевод накладывается на УЖЕ отрисованную разметку. Причина не в экономии:
   так строку физически нельзя забыть обернуть — наблюдатель видит любую
   вставку разметки, в том числе меню и модалки, которые рисуются мимо render().
   Непереведённая строка остаётся русской и сразу видна на английском экране.

   Речь, конспекты и названия записей в словаре отсутствуют, поэтому остаются
   на языке разговора — это данные, а не интерфейс. */
const L10N_ATTRS = ['placeholder', 'title', 'aria-label', 'data-tip'];
function localize(root) {
  if (LANG !== 'en' || !root) return;
  if (root.nodeType === 3) { swapText(root); return; }
  const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = [];
  for (let n = w.nextNode(); n; n = w.nextNode()) nodes.push(n);
  nodes.forEach(swapText);
  if (root.querySelectorAll) root.querySelectorAll('[' + L10N_ATTRS.join('],[') + ']').forEach(swapAttrs);
  if (root.getAttribute) swapAttrs(root);
}
function swapText(n) {
  const v = n.nodeValue, k = v.trim().replace(/\s+/g, ' ');   // переносы в разметке не мешают
  if (!k || !DICT[k]) return;
  if (n.__ru == null) n.__ru = v;              // запомнить русское, чтобы вернуть
  n.nodeValue = v.match(/^\s*/)[0] + DICT[k] + v.match(/\s*$/)[0];
}
function swapAttrs(el) {
  L10N_ATTRS.forEach(a => {
    const raw = el.getAttribute && el.getAttribute(a);
    const v = raw && raw.trim().replace(/\s+/g, ' ');
    if (!v || !DICT[v]) return;
    el.__ruAttrs = el.__ruAttrs || {};
    if (el.__ruAttrs[a] == null) el.__ruAttrs[a] = raw;
    el.setAttribute(a, DICT[v]);
  });
}
/* Возврат на русский. Разметку, которую рисует прототип, он перерисует сам, но
   постоянные части страницы (рамка окна, шапки модалок, переключатель окон)
   заново не рождаются — им русское возвращается из запомненного. */
function unlocalize(root) {
  const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  for (let n = w.nextNode(); n; n = w.nextNode()) if (n.__ru != null) n.nodeValue = n.__ru;
  root.querySelectorAll('*').forEach(el => {
    if (!el.__ruAttrs) return;
    L10N_ATTRS.forEach(a => { if (el.__ruAttrs[a] != null) el.setAttribute(a, el.__ruAttrs[a]); });
  });
}
/* Наблюдатель за вставками разметки. Правку самого текста он не отслеживает,
   поэтому перевод не вызывает сам себя. */
new MutationObserver(recs => {
  if (LANG !== 'en') return;
  recs.forEach(r => r.addedNodes.forEach(localize));
}).observe(document.documentElement, { childList: true, subtree: true });

/* Смена языка целиком: строки записей пересобрать, разметку перевести.
   Перерисовку экрана делает прототип — он знает, что у него открыто. */
function setLang(lang) {
  LANG = lang === 'en' ? 'en' : 'ru';
  document.documentElement.setAttribute('lang', LANG);
  applyLang();
  if (LANG === 'en') localize(document.body); else unlocalize(document.body);
}

