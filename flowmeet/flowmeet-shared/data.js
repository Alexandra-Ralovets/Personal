/* ВРЕМЯ ЗАПИСЕЙ СЧИТАЕТСЯ ОТ СЕГОДНЯШНЕГО ДНЯ, а не вписано датой (правка
   28.08.2026). Вписанная дата вмораживает корпус: через неделю после правки
   самая свежая встреча оказывается недельной давности, групп «Сегодня» и
   «Вчера» в списке не бывает вовсе, и приложение выглядит заброшенным. При этом
   записи на диктофоне время считали от «сейчас» с самого начала — значит
   владельцев понятия «когда» было два, и они разъезжались каждый день.
   Решение «корпус при каждом открытии одинаков» это не отменяет: оно про
   отсутствие случайных чисел, и оно в силе — смещения по-прежнему выводятся из
   номера записи, корпус одинаков в пределах дня. */
const dayAgo = (days, h, m) => {
  const x = new Date();
  x.setDate(x.getDate() - days);
  x.setHours(h, m, 0, 0);
  return x.getTime();
};

