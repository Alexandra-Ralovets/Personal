/* Расход и вся статистика выводятся ИЗ ЗАПИСЕЙ: числами в разметке они
   разъезжаются с таблицей при первом же изменении корпуса (стояло «287
   записей» при шести на экране). Величина политики здесь одна — лимит,
   его задаёт администратор пространства, из данных он не выводится. */
const LIMIT_MIN = 1200;                                  // минут в месяц на пространство
const monthKey = f => { const d = new Date(f.ts); return d.getFullYear() * 100 + d.getMonth() + 1; };
const dayKey = f => { const d = new Date(f.ts); return monthKey(f) * 100 + d.getDate(); };
const stats = () => {
  const a = alive();
  const mons = [...new Set(a.map(monthKey))].sort((x, y) => x - y);
  const cur = mons[mons.length - 1], prev = mons[mons.length - 2];
  const minIn = m => Math.round(a.filter(f => monthKey(f) === m).reduce((t, f) => t + f.sec, 0) / 60);
  const used = cur ? minIn(cur) : 0, was = prev ? minIn(prev) : 0;
  const hours = a.reduce((t, f) => t + f.sec, 0) / 3600;
  const days = new Set(a.map(dayKey)).size;
  const byHour = {};
  a.forEach(f => { const h = new Date(f.ts).getHours(); byHour[h] = (byHour[h] || 0) + 1; });
  const peak = Object.keys(byHour).sort((x, y) => byHour[y] - byHour[x])[0];
  const renew = cur ? new Date(Math.floor(cur / 100) + (cur % 100 === 12 ? 1 : 0),
    cur % 100 === 12 ? 0 : cur % 100, 1) : null;
  return {
    n: a.length, hours, days, used, cur,
    left: Math.max(0, LIMIT_MIN - used),
    pct: Math.min(100, Math.round(used / LIMIT_MIN * 100)),
    /* Доля ОСТАТКА — ею залита полоса лимита (правка 28.08.2026). Полоса стояла
       на `pct`, то есть на израсходованном, а подпись рядом говорит «осталось
       552 из 1200»: заливка означала противоположное подписи. Рядом на экране
       диктофона такая же полоса заряда залита остатком — три одинаковых полосы
       в одном интерфейсе обязаны читаться одинаково. */
    leftPct: Math.max(0, Math.min(100, Math.round((LIMIT_MIN - used) / LIMIT_MIN * 100))),
    delta: was ? Math.round((used - was) / was * 100) : null,
    perDay: days ? hours / days : 0,
    peak: peak ? p2(+peak) + ':00–' + p2(+peak + 1) + ':00' : '—',
    renew: renew ? fmtDate(renew.getTime()).replace(/[,]?\s*\d{2}:\d{2}$/, '') : '—'
  };
};

