const MONS_EN = ['Jan','Feb','Mar','Apr','May','Jun','Jul','Aug','Sep','Oct','Nov','Dec'];
const p2 = n => String(n).padStart(2, '0');

/* ЕДИНСТВЕННЫЙ владелец времени записи — числа `ts` (когда) и `sec` (сколько).
   Строки `date`, `dur`, `total` из них ВЫВОДЯТСЯ и пересобираются при смене
   языка. Раньше владельцем была строка, и её приходилось разбирать обратно
   при каждой сортировке — от этого зависела правильность порядка. */
const fmtDate = ts => {
  const d = new Date(ts);
  return LANG === 'en'
    ? `${d.getDate()} ${MONS_EN[d.getMonth()]} ${d.getFullYear()}, ${p2(d.getHours())}:${p2(d.getMinutes())}`
    : `${p2(d.getDate())}.${p2(d.getMonth() + 1)}.${d.getFullYear()} ${p2(d.getHours())}:${p2(d.getMinutes())}`;
};
const fmtTotal = sec => {                          // часы на плеере, язык не важен
  const h = Math.floor(sec / 3600), m = Math.floor(sec % 3600 / 60), c = Math.round(sec % 60);
  return h ? `${h}:${p2(m)}:${p2(c)}` : `${p2(m)}:${p2(c)}`;
};
const fmtDur = sec => {
  const h = Math.floor(sec / 3600), m = Math.floor(sec % 3600 / 60), c = Math.round(sec % 60);
  return LANG === 'en'
    ? (h ? `${h} h ` : '') + `${m} min ${c} s`
    : (h ? `${h} ч ` : '') + `${m} мин ${c} с`;
};
/* Короткая дата для узких мест (колонка списка): день, месяц и время. Резать
   готовую строку нельзя — в двух языках она разной формы. */
const fmtShort = ts => {
  const d = new Date(ts);
  return (LANG === 'en' ? `${d.getDate()} ${MONS_EN[d.getMonth()]}` : `${p2(d.getDate())}.${p2(d.getMonth() + 1)}`)
    + ` ${p2(d.getHours())}:${p2(d.getMinutes())}`;
};
/* Короткая длительность для списка: секунды в перечне не нужны, а место
   отнимают — из-за них подпись строки не влезала в ширину телефона. */
const fmtDurShort = sec => {
  const h = Math.floor(sec / 3600), m = Math.round(sec % 3600 / 60);
  return LANG === 'en' ? (h ? `${h} h ${m} min` : `${m} min`) : (h ? `${h} ч ${m} мин` : `${m} мин`);
};
/* Подпись группы записей по времени: «Сегодня», «Вчера», внутри недели — день
   недели с датой, дальше — дата, за пределами текущего года — с годом.
   Живёт здесь, а не в разметке прототипа: вывод даты — интерфейс, у него один
   владелец на оба прототипа. Названия дней и месяцев берём у самого языка,
   а не своим перечнем: свой перечень пришлось бы держать на двух языках. */
const dayStart = ts => { const d = new Date(ts); return new Date(d.getFullYear(), d.getMonth(), d.getDate()).getTime(); };
const capFirst = s => s.charAt(0).toUpperCase() + s.slice(1);
const fmtDayGroup = (ts, now) => {
  const loc = LANG === 'en' ? 'en-US' : 'ru-RU';
  const today = dayStart(now === undefined ? Date.now() : now);
  const diff = Math.round((today - dayStart(ts)) / 86400000);
  if (diff === 0) return LANG === 'en' ? 'Today' : 'Сегодня';
  if (diff === 1) return LANG === 'en' ? 'Yesterday' : 'Вчера';
  const d = new Date(ts);
  if (diff > 1 && diff < 7) return capFirst(d.toLocaleDateString(loc, { weekday: 'long', day: 'numeric', month: 'long' }));
  const opts = { day: 'numeric', month: 'long' };
  if (d.getFullYear() !== new Date(today).getFullYear()) opts.year = 'numeric';
  return capFirst(d.toLocaleDateString(loc, opts));
};
